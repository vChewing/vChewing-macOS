// 本檔為雙拼方案編輯器之資料模型：AppKit 與 SwiftUI 兩版渲染器共用。
// 刻意只依賴 `Foundation` 與引擎（`Arimitsu`），不碰 SwiftUI／AppKit，
// 故 5.10 路徑亦可編譯、亦得於單元測試內直接驅動。

import Arimitsu
import Foundation

// MARK: - DualpinSchemaTemplate

/// 方案編輯器之起始範本。
public enum DualpinSchemaTemplate: String, CaseIterable, Sendable {
  /// 空白：以唯音兩內建方案之兩表之聯集為骨架。
  case blank
  /// 微軟雙拼（`DualpinParser.mspy`）之副本。
  case microsoft
  /// GB/T 34947-2017（`DualpinParser.gbt17`）之副本。
  case gbt17
  /// 目前偏好設定內之自訂方案之副本。
  case current
}

// MARK: - DualpinEditorTable

/// 雙拼之兩張表。
public enum DualpinEditorTable: String, CaseIterable, Sendable {
  /// 聲母表。
  case initials
  /// 尾綴表。
  case finals
}

// MARK: - DualpinSchemaDraft

/// 一份「正在編輯中」之雙拼方案。
///
/// 欄位與 `DualpinParser` 逐一對位，故可無損往返；惟 `alphabet` 係引擎之推導值、
/// 不在此存續。序號欄位（`overrides`／`aliases`／`acknowledgedUnreachable`／
/// `keyInterception`／`autochopPolicy`）本版界面不開放編輯，惟一律照原樣攜帶，
/// 以免儲存時被靜默丟棄。
public struct DualpinSchemaDraft: Equatable, Sendable {
  // MARK: Lifecycle

  public init(
    rawID: String,
    rawTitle: String,
    localizedTitle: [String: String] = [:],
    initials: [String: Character],
    finals: [String: Character],
    nullOnset: DualpinParser.NullOnsetPolicy,
    keyInterception: DualpinParser.KeyInterception = .none,
    autochopPolicy: DualpinParser.AutochopPolicy = .disabled,
    overrides: [String: String] = [:],
    aliases: [String: String] = [:],
    acknowledgedUnreachable: Set<String> = [],
    schemaURLString: String? = nil,
    isRawIDAutoGenerated: Bool = false
  ) {
    self.rawID = rawID
    self.rawTitle = rawTitle
    self.localizedTitle = localizedTitle
    self.initials = initials
    self.finals = finals
    self.nullOnset = nullOnset
    self.keyInterception = keyInterception
    self.autochopPolicy = autochopPolicy
    self.overrides = overrides
    self.aliases = aliases
    self.acknowledgedUnreachable = acknowledgedUnreachable
    self.schemaURLString = schemaURLString
    self.isRawIDAutoGenerated = isRawIDAutoGenerated
  }

  /// 自既有方案起稿（欄位逐一照抄）。
  public init(parser: DualpinParser, schemaURLString: String? = nil) {
    self.init(
      rawID: parser.rawID,
      rawTitle: parser.rawTitle,
      localizedTitle: parser.localizedTitle,
      initials: parser.initials,
      finals: parser.finals,
      nullOnset: parser.nullOnset,
      keyInterception: parser.keyInterception,
      autochopPolicy: parser.autochopPolicy,
      overrides: parser.overrides,
      aliases: parser.aliases,
      acknowledgedUnreachable: parser.acknowledgedUnreachable,
      schemaURLString: schemaURLString
    )
  }

  // MARK: Public

  /// 方案之 DNS 名唯一 ID。
  public var rawID: String
  /// 方案名稱（各語系標題之 fallback 源）。
  public var rawTitle: String
  /// 各語系標題（本版界面不開放編輯，惟照原樣攜帶）。
  public var localizedTitle: [String: String]
  /// 聲母表。
  public var initials: [String: Character]
  /// 尾綴表。
  public var finals: [String: Character]
  /// 零聲母政策。
  public var nullOnset: DualpinParser.NullOnsetPolicy
  /// 主機保留鍵之攔截政策。
  public var keyInterception: DualpinParser.KeyInterception
  /// 自動截斷政策。
  public var autochopPolicy: DualpinParser.AutochopPolicy
  /// 碼之覆寫。
  public var overrides: [String: String]
  /// 別名。
  public var aliases: [String: String]
  /// 已知無碼且不追究之詞幹。
  public var acknowledgedUnreachable: Set<String>
  /// 原檔案之 `$schema` 值。儲存／匯出時置首。
  public var schemaURLString: String?
  /// `rawID` 是否仍隨名稱自動生成（使用者手改 `rawID` 之後即不再連動）。
  public private(set) var isRawIDAutoGenerated: Bool

  /// 目前草稿對應之方案。
  public var parser: DualpinParser {
    DualpinParser(
      rawID: rawID,
      rawTitle: rawTitle,
      localizedTitle: localizedTitle,
      initials: initials,
      finals: finals,
      nullOnset: nullOnset,
      keyInterception: keyInterception,
      autochopPolicy: autochopPolicy,
      overrides: overrides,
      aliases: aliases,
      acknowledgedUnreachable: acknowledgedUnreachable
    )
  }

  // MARK: - 起稿

  /// 依範本起稿。
  ///
  /// 內建範本（微軟／GB/T）之兩表與政策照抄，惟名稱一律留白、`rawID` 改發
  /// `dualPin.User.<slug>`：內建方案之四語標題與 `rawID` 不該被使用者之副本沿用
  /// （前者會誤導、後者會觸發 `E9`）。
  public static func make(
    template: DualpinSchemaTemplate,
    current: DualpinParser?,
    schemaURLString: String? = nil
  )
    -> Self {
    switch template {
    case .blank:
      return Self(
        rawID: autoRawID(forTitle: ""),
        rawTitle: "",
        initials: mergedTables(of: [DualpinParser.mspy, DualpinParser.gbt17]).initials,
        finals: mergedTables(of: [DualpinParser.mspy, DualpinParser.gbt17]).finals,
        nullOnset: .fixedKey("o"),
        schemaURLString: schemaURLString,
        isRawIDAutoGenerated: true
      )
    case .microsoft:
      return make(builtin: DualpinParser.mspy, schemaURLString: schemaURLString)
    case .gbt17:
      return make(builtin: DualpinParser.gbt17, schemaURLString: schemaURLString)
    case .current:
      guard let current else {
        return make(template: .blank, current: nil, schemaURLString: schemaURLString)
      }
      return Self(parser: current, schemaURLString: schemaURLString)
    }
  }

  /// 依名稱生成 `rawID`：ASCII 英數以外之字元一律化為連字號；
  /// 結果為空（例如名稱全為漢字）時退回 `Custom`。
  public static func autoRawID(forTitle title: String) -> String {
    var slug = ""
    for scalar in title.lowercased().unicodeScalars {
      switch scalar {
      case "0" ... "9", "a" ... "z":
        slug.unicodeScalars.append(scalar)
      default:
        guard !slug.isEmpty, !slug.hasSuffix("-") else { break }
        slug += "-"
      }
    }
    slug = slug.trimmingCharacters(in: CharacterSet(charactersIn: "-"))
    return "dualPin.User." + (slug.isEmpty ? "Custom" : slug)
  }

  /// 以引擎校驗本草稿。
  ///
  /// 界面一律轉述本報告之結論，不自行實作任何檢證邏輯。
  public func validateReport(
    conflictingRawIDs: Set<String> = DualpinParser.builtinRawIDs
  )
    -> DualpinValidationReport {
    parser.validate(conflictingRawIDs: conflictingRawIDs)
  }

  // MARK: - 兩表之內容

  /// 指定表之音節（排序）。
  public func syllables(in table: DualpinEditorTable) -> [String] {
    switch table {
    case .initials: return initials.keys.sorted()
    case .finals: return finals.keys.sorted()
    }
  }

  /// 指定表之指定音節目前所用之按鍵。
  public func key(ofSyllable syllable: String, in table: DualpinEditorTable) -> Character? {
    switch table {
    case .initials: return initials[syllable]
    case .finals: return finals[syllable]
    }
  }

  /// 指定表內用及指定按鍵之音節（排序）。
  public func syllables(atKey key: Character, in table: DualpinEditorTable) -> [String] {
    let source = table == .initials ? initials : finals
    return source.filter { $0.value == key }.map(\.key).sorted()
  }

  // MARK: - 兩表之異動

  /// 將指定表之指定音節改配至指定按鍵。
  public mutating func assign(
    key: Character,
    toSyllable syllable: String,
    in table: DualpinEditorTable
  ) {
    switch table {
    case .initials:
      guard initials[syllable] != nil else { return }
      initials[syllable] = key
    case .finals:
      guard finals[syllable] != nil else { return }
      finals[syllable] = key
    }
  }

  /// 改動方案名稱。`rawID` 仍為自動生成時，隨名稱一併更新。
  public mutating func updateTitle(_ newTitle: String) {
    rawTitle = newTitle
    guard isRawIDAutoGenerated else { return }
    rawID = Self.autoRawID(forTitle: newTitle)
  }

  /// 手改 `rawID`（此後 `rawID` 不再隨名稱連動）。
  public mutating func updateRawID(_ newRawID: String) {
    rawID = newRawID
    isRawIDAutoGenerated = false
  }

  /// 改動零聲母政策。
  public mutating func updateNullOnset(_ newPolicy: DualpinParser.NullOnsetPolicy) {
    nullOnset = newPolicy
  }

  // MARK: Private

  private static func make(
    builtin: DualpinParser,
    schemaURLString: String?
  )
    -> Self {
    Self(
      rawID: autoRawID(forTitle: ""),
      rawTitle: "",
      initials: builtin.initials,
      finals: builtin.finals,
      nullOnset: builtin.nullOnset,
      keyInterception: builtin.keyInterception,
      autochopPolicy: builtin.autochopPolicy,
      overrides: builtin.overrides,
      aliases: builtin.aliases,
      acknowledgedUnreachable: builtin.acknowledgedUnreachable,
      schemaURLString: schemaURLString,
      isRawIDAutoGenerated: true
    )
  }

  /// 兩表之聯集：先到者勝（故前列者之既有鍵位不受後列者覆寫）。
  private static func mergedTables(
    of parsers: [DualpinParser]
  )
    -> (initials: [String: Character], finals: [String: Character]) {
    var initials: [String: Character] = [:]
    var finals: [String: Character] = [:]
    parsers.forEach { parser in
      parser.initials.forEach { if initials[$0.key] == nil { initials[$0.key] = $0.value } }
      parser.finals.forEach { if finals[$0.key] == nil { finals[$0.key] = $0.value } }
    }
    return (initials, finals)
  }
}

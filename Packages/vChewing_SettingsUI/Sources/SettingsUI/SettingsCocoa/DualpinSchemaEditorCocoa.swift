// MARK: - DualpinEditorKeyboardGridCocoa

/// 鍵位預覽格：三列（`QWERTYUIOP`／`ASDFGHJKL;`／`ZXCVBNM`），
/// 每格左上角小字＝鍵名，其下逐行列出該鍵之聲母（半粗體）與尾綴（各佔一行，故不受格寬所限）。
internal final class DualpinEditorKeyboardGridCocoa: NSView {
  // MARK: Internal

  override var isFlipped: Bool { true }

  override var intrinsicContentSize: NSSize {
    let width = CGFloat(DualpinEditorKeyboard.rows.first?.count ?? 0) * (cellWidth + spacing)
    let height = CGFloat(DualpinEditorKeyboard.rows.count) * (cellHeight + spacing)
    return NSSize(width: width, height: height)
  }

  var annotations: [DualpinEditorKeyAnnotation] = [] {
    didSet {
      invalidateIntrinsicContentSize()
      needsDisplay = true
    }
  }

  override func draw(_ dirtyRect: NSRect) {
    super.draw(dirtyRect)
    let map = Dictionary(
      uniqueKeysWithValues: annotations.map { ($0.key, $0) }
    )
    for (rowIndex, row) in DualpinEditorKeyboard.rows.enumerated() {
      for (columnIndex, key) in row.enumerated() {
        let rect = NSRect(
          x: CGFloat(columnIndex) * (cellWidth + spacing),
          y: CGFloat(rowIndex) * (cellHeight + spacing),
          width: cellWidth,
          height: cellHeight
        )
        drawCell(annotation: map[key], key: key, in: rect)
      }
    }
  }

  // MARK: Private

  private let cellWidth: CGFloat = 46
  private let cellHeight: CGFloat = 58
  private let lineHeight: CGFloat = 11
  private let spacing: CGFloat = 2

  private let syllableFont = NSFont.systemFont(ofSize: 9)

  /// 聲母用半粗體與尾綴區隔；`NSFont.systemFont(ofSize:weight:)` 係 10.11 起才有，故經字型管理員轉換。
  private var initialFont: NSFont {
    NSFontManager.shared.convert(syllableFont, toHaveTrait: .boldFontMask)
  }

  private var labelColor: NSColor {
    if #available(macOS 10.10, *) { return .labelColor }
    return .textColor
  }

  private var secondaryLabelColor: NSColor {
    if #available(macOS 10.10, *) { return .secondaryLabelColor }
    return .gray
  }

  private func drawCell(
    annotation: DualpinEditorKeyAnnotation?,
    key: Character,
    in rect: NSRect
  ) {
    let path = NSBezierPath(roundedRect: rect.insetBy(dx: 0.5, dy: 0.5), xRadius: 3, yRadius: 3)
    background(for: annotation).setFill()
    path.fill()
    NSColor.gray.withAlphaComponent(0.45).setStroke()
    path.lineWidth = 1
    path.stroke()

    draw(
      text: String(key),
      in: NSRect(x: rect.minX + 3, y: rect.minY + 1, width: rect.width - 6, height: 10),
      font: NSFont.systemFont(ofSize: 8),
      color: secondaryLabelColor,
      alignment: .left
    )
    let initials = annotation?.initialSyllables ?? []
    let finals = annotation?.finalSyllables ?? []
    var lines = initials.map { (text: $0, font: initialFont) }
    lines.append(contentsOf: finals.map { (text: $0, font: syllableFont) })
    if lines.isEmpty { lines = [(text: "—", font: syllableFont)] }
    for (index, line) in lines.enumerated() {
      draw(
        text: line.text,
        in: NSRect(
          x: rect.minX + 2,
          y: rect.minY + 11 + CGFloat(index) * lineHeight,
          width: rect.width - 4,
          height: lineHeight
        ),
        font: line.font,
        color: labelColor,
        alignment: .center
      )
    }
  }

  private func draw(
    text: String,
    in rect: NSRect,
    font: NSFont,
    color: NSColor,
    alignment: NSTextAlignment
  ) {
    let paragraphStyle = NSMutableParagraphStyle()
    paragraphStyle.alignment = alignment
    paragraphStyle.lineBreakMode = .byTruncatingTail
    let attributedString = NSAttributedString(
      string: text,
      attributes: [.font: font, .foregroundColor: color, .paragraphStyle: paragraphStyle]
    )
    attributedString.draw(in: rect)
  }

  private func background(for annotation: DualpinEditorKeyAnnotation?) -> NSColor {
    guard let annotation else { return .clear }
    if annotation.isReservedInUse { return NSColor.red.withAlphaComponent(0.12) }
    if annotation.isUnusedTableKey { return NSColor.orange.withAlphaComponent(0.10) }
    if annotation.isUsedByAnyCode { return NSColor.gray.withAlphaComponent(0.08) }
    return .clear
  }
}

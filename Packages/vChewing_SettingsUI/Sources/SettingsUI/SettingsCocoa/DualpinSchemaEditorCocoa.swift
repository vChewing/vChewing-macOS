// MARK: - DualpinSchemaEditorCocoa

/// 雙拼方案編輯器（AppKit 版）。
///
/// 始終展開、落於「鍵盤設定 → 雙拼方案」Section 之底端；素材全取自引擎之公開面與
/// `DualpinSchemaStore` 之序列化，界面不自算任何檢證結論。
///
/// - Attention: 檔案對話框一律遵守唯音之全域約定：**macOS 10.13 之前不開
///   `NSOpenPanel`／`NSSavePanel`**（ComDlg32 不可用，呼出即死桌面），匯出改走
///   `~/Library/Application Support/fileDump/` 之傾印。
public final class DualpinSchemaEditorCocoa: NSView, NSTextFieldDelegate {
  // MARK: Lifecycle

  public init(width: CGFloat, onChange: (() -> ())? = nil) {
    self.contentWidth = width
    self.onChange = onChange
    super.init(frame: .zero)
    translatesAutoresizingMaskIntoConstraints = false
    configureControls()
    let built = buildBody() ?? NSView()
    addSubview(built)
    built.pinEdges(to: self)
    makeSimpleConstraint(.width, relation: .equal, value: width)
    loadFromPreferences()
  }

  @available(*, unavailable)
  required init?(coder _: NSCoder) {
    fatalError("init(coder:) is not supported.")
  }

  // MARK: Public

  public func controlTextDidChange(_ obj: Notification) {
    guard let field = obj.object as? NSTextField else { return }
    switch field {
    case nameField:
      draft.updateTitle(String(nameField.stringValue.prefix(32)))
    case rawIDField:
      draft.updateRawID(rawIDField.stringValue)
    default:
      return
    }
    refreshUI()
  }

  // MARK: Private

  /// 指派列標題列之第一欄寬（對齊「聲母」「尾綴」兩列之表名）。
  private static let assignmentTableLabelWidth: CGFloat = 64

  private let contentWidth: CGFloat
  private let onChange: (() -> ())?

  private var draft: DualpinSchemaDraft = .init(
    rawID: DualpinSchemaDraft.autoRawID(forTitle: ""),
    rawTitle: "",
    initials: [:],
    finals: [:],
    nullOnset: .fixedKey("o"),
    isRawIDAutoGenerated: true
  )
  private var appliedTemplate: DualpinSchemaTemplate = .blank
  private var fixedNullOnsetKey: Character = "o"
  private var selectedInitialSyllable = ""
  private var selectedFinalSyllable = ""

  private let nameField = NSTextField()
  private let rawIDField = NSTextField()
  private let templatePopup = NSPopUpButton()
  private let nullOnsetModePopup = NSPopUpButton()
  private let nullOnsetKeyPopup = NSPopUpButton()
  private let initialSyllablePopup = NSPopUpButton()
  private let finalSyllablePopup = NSPopUpButton()
  private let initialKeyPopup = NSPopUpButton()
  private let finalKeyPopup = NSPopUpButton()
  private let initialHintLabel = NSAttributedString(string: "").makeNSLabel()
  private let finalHintLabel = NSAttributedString(string: "").makeNSLabel()
  private let keyboardGrid = DualpinEditorKeyboardGridCocoa()
  private let summaryLabel = NSAttributedString(string: "").makeNSLabel()
  private let codableLabel = NSAttributedString(string: "").makeNSLabel()
  /// 校驗明細鈕。明細改以 sheet 呈現（原本之展開盒見 `showValidationDetails(_:)` 之註解）。
  private lazy var detailsButton = NSButton(
    verbatim: DualpinEditorText.validationDetails + "…",
    target: self,
    action: #selector(showValidationDetails(_:))
  )
  // 三顆動作鈕一律走 DSL 之 `NSButton(verbatim:target:action:)`：該建構子會顯式宣告 Aqua
  // （`.rounded`）bezel 風格。裸 `NSButton()` 不宣告者，在 macOS 10.9 上不會自動取得此風格，
  // 而呈 Windows 2000 式之方角外觀。
  private lazy var saveButton = NSButton(
    verbatim: DualpinEditorText.save,
    target: self,
    action: #selector(saveDraft(_:))
  )
  private lazy var exportButton = NSButton(
    verbatim: DualpinEditorText.export,
    target: self,
    action: #selector(exportSchema(_:))
  )
  private lazy var revertButton = NSButton(
    verbatim: DualpinEditorText.revert,
    target: self,
    action: #selector(revertDraft(_:))
  )
  private let statusLabel = NSAttributedString(string: "").makeNSLabel()
  /// 最近一次校驗之報告：供「校驗明細」鈕以 sheet 呈現。
  private var lastValidationReport: DualpinValidationReport?

  /// 「零聲母鍵」整列（含其上之分隔線）隨零聲母政策之固定鍵與否整列收放。
  private lazy var nullOnsetKeyDivider = makeSeparator()
  private lazy var nullOnsetKeyRow: NSStackView? = fillWidth(
    [makeRowLabel(DualpinEditorText.nullOnsetKey, width: contentWidth * 0.6), nullOnsetKeyPopup]
      .stack(.horizontal, spacing: 6)
  )

  private var labelColor: NSColor {
    if #available(macOS 10.10, *) { return .labelColor }
    return .textColor
  }

  private var secondaryLabelColor: NSColor {
    if #available(macOS 10.10, *) { return .secondaryLabelColor }
    return .gray
  }

  // MARK: 控制項之組態

  private func configureControls() {
    // 兩欄文字欄一律靠右對齊（比照 SwiftUI 版之 `.multilineTextAlignment(.trailing)`），
    // 寬度由 `identityRows()` 依容器寬配發。
    // `NSTextField.placeholderString` 係 10.10+，故經 cell 設定（比照
    // `SettingsCocoa/VwrSettingsPaneCocoaPhrases.swift` 之作法）。
    (nameField.cell as? NSTextFieldCell)?.placeholderString = DualpinEditorText.namePlaceholder
    nameField.alignment = .right
    nameField.delegate = self
    nameField.target = self
    nameField.action = #selector(nameFieldCommitted(_:))

    rawIDField.alignment = .right
    rawIDField.delegate = self
    rawIDField.target = self
    rawIDField.action = #selector(rawIDFieldCommitted(_:))
    rawIDField.font = NSFont.userFixedPitchFont(ofSize: NSFont.smallSystemFontSize)

    templatePopup.target = self
    templatePopup.action = #selector(templateChanged(_:))
    templatePopup.removeAllItems()
    templatePopup.addItems(withTitles: DualpinSchemaTemplate.allCases.map(DualpinEditorText.templateName))

    nullOnsetModePopup.target = self
    nullOnsetModePopup.action = #selector(nullOnsetModeChanged(_:))
    nullOnsetModePopup.removeAllItems()
    nullOnsetModePopup.addItems(
      withTitles: DualpinNullOnsetMode.allCases.map(DualpinEditorText.nullOnsetModeName)
    )

    nullOnsetKeyPopup.target = self
    nullOnsetKeyPopup.action = #selector(nullOnsetKeyChanged(_:))
    nullOnsetKeyPopup.removeAllItems()
    nullOnsetKeyPopup.addItems(withTitles: DualpinEditorKeyboard.allKeys.map(DualpinEditorText.keyLabel))

    [initialSyllablePopup, finalSyllablePopup].forEach {
      $0.target = self
      $0.removeAllItems()
    }
    initialSyllablePopup.action = #selector(initialSyllableChanged(_:))
    finalSyllablePopup.action = #selector(finalSyllableChanged(_:))

    [initialKeyPopup, finalKeyPopup].forEach {
      $0.target = self
      $0.removeAllItems()
    }
    initialKeyPopup.action = #selector(initialKeyChanged(_:))
    finalKeyPopup.action = #selector(finalKeyChanged(_:))

    [initialHintLabel, finalHintLabel, summaryLabel, codableLabel, statusLabel].forEach {
      $0.preferredMaxLayoutWidth = contentWidth
    }
    codableLabel.textColor = secondaryLabelColor
    statusLabel.textColor = secondaryLabelColor
  }

  // MARK: 版面

  /// 各區塊間之橫貫分隔線（比照 SwiftUI 版之 `Divider()`）。
  private func makeSeparator() -> NSView {
    let divider = NSView()
    divider.wantsLayer = true
    divider.layer?.backgroundColor = NSColor.gray.withAlphaComponent(0.2).cgColor
    divider.translatesAutoresizingMaskIntoConstraints = false
    divider.makeSimpleConstraint(.height, relation: .equal, value: 1)
    divider.makeSimpleConstraint(.width, relation: .equal, value: contentWidth)
    return divider
  }

  /// 行標籤：佔容器寬之定比，行內之控件隨後（控制項一律靠右）。
  private func makeRowLabel(_ text: String, width: CGFloat) -> NSLabelView {
    let label = text.makeNSLabel()
    label.makeSimpleConstraint(.width, relation: .equal, value: width)
    return label
  }

  /// 令整列撐滿容器寬。`NSStackView` 之 `.equalSpacing` 只把餘寬塞進「間隙」，不拉伸控件本身，
  /// 故列若聽憑內含控件之固有寬度，貼右之控件（如範本彈出鈕）便會停在半途；
  /// 撐滿容器後：兩控件之列＝餘寬盡歸唯一間隙（控件貼右），
  /// 三控件之列（左右各一空白＋居中物）＝兩道間隙等分（居中物真正居中）。
  @discardableResult
  private func fillWidth<T: NSView>(_ row: T?) -> T? {
    row?.makeSimpleConstraint(.width, relation: .equal, value: contentWidth)
    return row
  }

  /// 將單一控件靠右塞進定寬之欄位（令指派列與其標題列逐欄對位）。
  private func makeColumn(_ view: NSView, width: CGFloat) -> NSView? {
    guard let column = [NSView(), view].stack(.horizontal, spacing: 0) else { return nil }
    column.makeSimpleConstraint(.width, relation: .equal, value: width)
    return column
  }

  private func buildBody() -> NSView? {
    let rows: [NSView?] = [
      identityRows(),
      makeSeparator(),
      templateRow(),
      makeSeparator(),
      nullOnsetRows(),
      makeSeparator(),
      keyboardPreview(),
      makeSeparator(),
      assignments(),
      makeSeparator(),
      validation(),
      makeSeparator(),
      actionRow(),
      statusLabel,
    ]
    let stack = rows.compactMap { $0 }
      .stack(.vertical, spacing: NSFont.systemFontSize / 2, insets: .new(all: 0))
    stack?.alignment = .leading
    return stack
  }

  private func identityRows() -> NSView? {
    let labelWidth = contentWidth * 0.4
    let fieldWidth = contentWidth - labelWidth - 6
    nameField.makeSimpleConstraint(.width, relation: .equal, value: fieldWidth)
    rawIDField.makeSimpleConstraint(.width, relation: .equal, value: fieldWidth)
    let nameRow = [makeRowLabel(DualpinEditorText.name, width: labelWidth), nameField]
      .stack(.horizontal, spacing: 6)
    let rawIDRow = [makeRowLabel(DualpinEditorText.rawID, width: labelWidth), rawIDField]
      .stack(.horizontal, spacing: 6)
    // 比照 SwiftUI 版之 `.font(.caption)`＋`.secondary`：小號字＋次級色。
    let helpLabel = DualpinEditorText.rawIDHelp.makeNSLabel(descriptive: true, fixWidth: contentWidth)
    return [nameRow, makeSeparator(), rawIDRow, helpLabel]
      .compactMap { $0 }
      .stack(.vertical, spacing: 4, insets: .new(all: 0))
  }

  private func templateRow() -> NSView? {
    fillWidth(
      [makeRowLabel(DualpinEditorText.template, width: contentWidth * 0.6), templatePopup]
        .stack(.horizontal, spacing: 6)
    )
  }

  private func nullOnsetRows() -> NSView? {
    let modeRow = fillWidth(
      [makeRowLabel(DualpinEditorText.nullOnsetMode, width: contentWidth * 0.6), nullOnsetModePopup]
        .stack(.horizontal, spacing: 6)
    )
    return [modeRow, nullOnsetKeyDivider, nullOnsetKeyRow]
      .compactMap { $0 }
      .stack(.vertical, spacing: 4, insets: .new(all: 0))
  }

  private func keyboardPreview() -> NSView? {
    let titleLabel = DualpinEditorText.keyboardPreview.makeNSLabel(fixWidth: contentWidth - 20)
    // 兩側各夾一等寬之空白視圖，令鍵位格真正居中（比照 SwiftUI 版之
    // `.frame(maxWidth: .infinity, alignment: .center)`）。不倚賴 `.equalSpacing`
    // 去等分餘寬——它會依 hugging 優先級拉伸其中之一，結果仍偏右。
    let gridWidth = keyboardGrid.intrinsicContentSize.width
    let side = max(0, (contentWidth - gridWidth) / 2)
    let leftSpacer = NSView()
    let rightSpacer = NSView()
    [leftSpacer, rightSpacer].forEach {
      $0.makeSimpleConstraint(.width, relation: .equal, value: side)
    }
    let centered = [leftSpacer, keyboardGrid, rightSpacer].stack(.horizontal, spacing: 0)
    return [titleLabel, centered].compactMap { $0 }
      .stack(.vertical, spacing: 4, insets: .new(all: 0))
  }

  private func assignments() -> NSView? {
    let tableLabelWidth = Self.assignmentTableLabelWidth
    let columnSpacing: CGFloat = 4
    let syllableColumnWidth = contentWidth * 0.22
    let keyColumnWidth = contentWidth * 0.22
    let hintColumnWidth =
      contentWidth - tableLabelWidth - syllableColumnWidth - keyColumnWidth - columnSpacing * 3
    [initialHintLabel, finalHintLabel].forEach {
      $0.makeSimpleConstraint(.width, relation: .equal, value: hintColumnWidth)
    }
    let tableSpacer = NSView()
    tableSpacer.makeSimpleConstraint(.width, relation: .equal, value: tableLabelWidth)
    let headerRow = [
      tableSpacer,
      makeColumn(
        DualpinEditorText.assignmentSyllable.makeNSLabel(descriptive: true),
        width: syllableColumnWidth
      ),
      makeColumn(
        DualpinEditorText.assignmentKey.makeNSLabel(descriptive: true),
        width: keyColumnWidth
      ),
      NSView(),
    ]
    .compactMap { $0 }
    .stack(.horizontal, spacing: columnSpacing)
    let rows: [NSView?] = [
      headerRow,
      assignmentRow(
        table: .initials,
        syllablePopup: initialSyllablePopup,
        keyPopup: initialKeyPopup,
        hintLabel: initialHintLabel,
        widths: (tableLabelWidth, syllableColumnWidth, keyColumnWidth),
        spacing: columnSpacing
      ),
      assignmentRow(
        table: .finals,
        syllablePopup: finalSyllablePopup,
        keyPopup: finalKeyPopup,
        hintLabel: finalHintLabel,
        widths: (tableLabelWidth, syllableColumnWidth, keyColumnWidth),
        spacing: columnSpacing
      ),
    ]
    let stack = rows.compactMap { $0 }.stack(.vertical, spacing: 4, insets: .new(all: 0))
    stack?.alignment = .leading
    return stack
  }

  private func assignmentRow(
    table: DualpinEditorTable,
    syllablePopup: NSPopUpButton,
    keyPopup: NSPopUpButton,
    hintLabel: NSLabelView,
    widths: (table: CGFloat, syllable: CGFloat, key: CGFloat),
    spacing: CGFloat
  )
    -> NSView? {
    let arrowLabel = NSAttributedString(string: "→").makeNSLabel()
    let keyColumn = [arrowLabel, keyPopup].stack(.horizontal, spacing: 4)
    return [
      makeRowLabel(DualpinEditorText.tableName(table), width: widths.table),
      makeColumn(syllablePopup, width: widths.syllable),
      keyColumn.flatMap { makeColumn($0, width: widths.key) },
      hintLabel,
    ]
    .compactMap { $0 }
    .stack(.horizontal, spacing: spacing)
  }

  private func validation() -> NSView? {
    let textColumn = [summaryLabel, codableLabel]
      .compactMap { $0 }
      .stack(.vertical, spacing: 2, insets: .new(all: 0))
    textColumn?.alignment = .leading
    let row = [detailsButton, textColumn].compactMap { $0 }.stack(.horizontal, spacing: 8)
    row?.alignment = .top
    return row
  }

  private func actionRow() -> NSView? {
    // 尾端補一空白視圖：三顆按鈕先自成一疊（不隨容器寬平均散開），再由此空白視圖吃掉餘寬。
    let buttons = [saveButton, exportButton, revertButton].stack(.horizontal, spacing: 8)
    return fillWidth([buttons, NSView()].compactMap { $0 }.stack(.horizontal, spacing: 0))
  }

  // MARK: 重繪

  private func refreshUI() {
    let report = draft.validateReport()
    if nameField.stringValue != draft.rawTitle { nameField.stringValue = draft.rawTitle }
    if rawIDField.stringValue != draft.rawID { rawIDField.stringValue = draft.rawID }

    let initialSyllables = draft.syllables(in: .initials)
    let finalSyllables = draft.syllables(in: .finals)
    if !initialSyllables.contains(selectedInitialSyllable) {
      selectedInitialSyllable = initialSyllables.first ?? ""
    }
    if !finalSyllables.contains(selectedFinalSyllable) {
      selectedFinalSyllable = finalSyllables.first ?? ""
    }

    fill(popup: initialSyllablePopup, titles: initialSyllables, selecting: selectedInitialSyllable)
    fill(popup: finalSyllablePopup, titles: finalSyllables, selecting: selectedFinalSyllable)
    refreshKeyPopup(
      popup: initialKeyPopup, table: .initials, syllable: selectedInitialSyllable
    )
    refreshKeyPopup(popup: finalKeyPopup, table: .finals, syllable: selectedFinalSyllable)
    initialHintLabel.attributedStringValue = .init(
      string: occupiedHint(table: .initials, syllable: selectedInitialSyllable)
    )
    finalHintLabel.attributedStringValue = .init(
      string: occupiedHint(table: .finals, syllable: selectedFinalSyllable)
    )
    initialHintLabel.textColor = secondaryLabelColor
    finalHintLabel.textColor = secondaryLabelColor

    let mode = DualpinNullOnsetMode(draft.nullOnset)
    nullOnsetModePopup.selectItem(at: DualpinNullOnsetMode.allCases.firstIndex(of: mode) ?? 0)
    fixedNullOnsetKey = draft.nullOnset.fixedKeyCharacter ?? fixedNullOnsetKey
    let isFixedKey = mode == .fixedKey
    nullOnsetKeyDivider.isHidden = !isFixedKey
    nullOnsetKeyRow?.isHidden = !isFixedKey
    if let index = DualpinEditorKeyboard.allKeys.firstIndex(of: fixedNullOnsetKey) {
      nullOnsetKeyPopup.selectItem(at: index)
    }

    templatePopup.selectItem(at: DualpinSchemaTemplate.allCases.firstIndex(of: appliedTemplate) ?? 0)
    keyboardGrid.annotations = draft.keyAnnotations(report: report)
    refreshValidation(report)
  }

  private func refreshValidation(_ report: DualpinValidationReport) {
    lastValidationReport = report
    summaryLabel.attributedStringValue = .init(string: DualpinEditorText.validationSummary(report))
    summaryLabel.textColor = report.isUsable ? labelColor : .red
    codableLabel.attributedStringValue = .init(string: DualpinEditorText.codableSummary(report))
    saveButton.isEnabled = report.isUsable
    exportButton.isEnabled = report.isUsable
  }

  private func fill(popup: NSPopUpButton, titles: [String], selecting title: String?) {
    popup.removeAllItems()
    popup.addItems(withTitles: titles)
    guard let title, let index = titles.firstIndex(of: title) else { return }
    popup.selectItem(at: index)
  }

  private func refreshKeyPopup(popup: NSPopUpButton, table: DualpinEditorTable, syllable: String) {
    let titles = DualpinEditorKeyboard.allKeys.map { key in
      let occupied = draft.syllables(atKey: key, in: table).filter { $0 != syllable }
      guard !occupied.isEmpty else { return DualpinEditorText.keyLabel(key) }
      return DualpinEditorText.keyLabel(key) + "　" + String(
        format: "i18n:Settings.DualpinEditor.Assignment.KeyTaken:%@".i18n,
        arguments: [occupied.joined(separator: "／")]
      )
    }
    fill(popup: popup, titles: titles, selecting: nil)
    guard let key = draft.key(ofSyllable: syllable, in: table),
          let index = DualpinEditorKeyboard.allKeys.firstIndex(of: key)
    else { return }
    popup.selectItem(at: index)
  }

  private func occupiedHint(table: DualpinEditorTable, syllable: String) -> String {
    guard let key = draft.key(ofSyllable: syllable, in: table) else { return "" }
    let others = draft.syllables(atKey: key, in: table).filter { $0 != syllable }
    guard !others.isEmpty else { return "" }
    return String(
      format: "i18n:Settings.DualpinEditor.Assignment.KeyTaken:%@".i18n,
      arguments: [others.joined(separator: "／")]
    )
  }

  private func setStatus(_ text: String) {
    statusLabel.attributedStringValue = .init(string: text)
    statusLabel.textColor = secondaryLabelColor
    // 比照 SwiftUI 版：無話可說時不留空行。
    statusLabel.isHidden = text.isEmpty
  }

  // MARK: 起稿與動作

  private func loadFromPreferences() {
    let schemaURL = DualpinSchemaStore.currentSchemaURLString
      ?? DualpinSchemaStore.canonicalSchemaURLString
    if let current = DualpinSchemaStore.currentParser {
      draft = DualpinSchemaDraft(parser: current, schemaURLString: schemaURL)
      appliedTemplate = .current
    } else {
      draft = DualpinSchemaDraft.make(template: .blank, current: nil, schemaURLString: schemaURL)
      appliedTemplate = .blank
    }
    fixedNullOnsetKey = draft.nullOnset.fixedKeyCharacter ?? "o"
    selectedInitialSyllable = draft.syllables(in: .initials).first ?? ""
    selectedFinalSyllable = draft.syllables(in: .finals).first ?? ""
    setStatus("")
    refreshUI()
  }

  private func applyTemplate(_ template: DualpinSchemaTemplate) {
    let schemaURL = DualpinSchemaStore.currentSchemaURLString
      ?? DualpinSchemaStore.canonicalSchemaURLString
    draft = DualpinSchemaDraft.make(
      template: template,
      current: DualpinSchemaStore.currentParser,
      schemaURLString: schemaURL
    )
    appliedTemplate = template
    selectedInitialSyllable = ""
    selectedFinalSyllable = ""
    fixedNullOnsetKey = draft.nullOnset.fixedKeyCharacter ?? fixedNullOnsetKey
    setStatus("")
    refreshUI()
  }

  private func confirmTemplate(_ template: DualpinSchemaTemplate) {
    let alert = NSAlert()
    alert.messageText = DualpinEditorText.template
    alert.informativeText = DualpinEditorText.templateName(template)
    alert.addButton(withTitle: "i18n:Common.OK".i18n)
    alert.addButton(withTitle: "i18n:Common.Cancel".i18n)
    alert.beginSheetModal(at: CtlSettingsCocoa.shared?.window) { [weak self] response in
      guard let self else { return }
      guard response == .alertFirstButtonReturn else {
        refreshUI()
        return
      }
      applyTemplate(template)
    }
  }

  /// 以 sheet 顯示最近一次校驗之全文（明細諸行與 DIPE 註記）。
  ///
  /// 原本的「進階」展開盒是 `NSBox` ＋ `isHidden`：`boxed()` 在**建立**該盒時即量測 `fittingSize`，
  /// 而彼時明細尚未填入，故高度下限趨近於零；之後才填進去的明細並不會把盒撐開，
  /// 盒遂在 macOS 10.9 上恆坍縮成一條線。改以 sheet 呈現，避開此一依賴 AppKit 版面時機的寫法。
  /// 明細行數不定（錯誤＋警告），故用可捲動之 accessory view，不塞 `informativeText`。
  @objc
  private func showValidationDetails(_: NSButton) {
    let report = lastValidationReport ?? draft.validateReport()
    let lines = [DualpinEditorText.validationSummary(report), DualpinEditorText.codableSummary(report)]
      + (report.errors + report.warnings).map(DualpinEditorText.issueLine)
      + [DualpinEditorText.validationDIPENote]
    let alert = NSAlert()
    alert.messageText = DualpinEditorText.validationDetails
    alert.addButton(withTitle: "i18n:Common.OK".i18n)
    alert.accessoryView = makeValidationDetailsView(text: lines.joined(separator: "\n"))
    alert.beginSheetModal(at: CtlSettingsCocoa.shared?.window)
  }

  /// 校驗明細之可捲動唯讀文字區。
  ///
  /// 內容寬須**自行扣掉右側垂直捲動條所佔的寬度**：`NSScrollView.contentSize` 在 overlay 捲動條樣式
  /// （macOS 10.13 以後的預設）下並不預留捲動條的寬度，浮動捲動條會壓在文字右緣；而若把文字視圖
  /// 設成與 scroll view 等寬、且允許橫向捲動，則 `NSClipView` 一旦橫向偏移，左緣就會被裁掉
  /// （事主 m07059 之截圖）。故固定以扣除捲動條寬度後的寬度令文字換行，並只允許縱向捲動。
  private func makeValidationDetailsView(text: String) -> NSView {
    let scrollView = NSScrollView(frame: .init(x: 0, y: 0, width: 440, height: 210))
    scrollView.borderType = .bezelBorder
    scrollView.hasVerticalScroller = true
    scrollView.hasHorizontalScroller = false
    scrollView.autohidesScrollers = false
    let scrollerRoom = NSScroller.scrollerWidth(for: .regular, scrollerStyle: .legacy)
    let contentSize = NSSize(
      width: max(80, scrollView.contentSize.width - scrollerRoom),
      height: scrollView.contentSize.height
    )
    let textView = NSTextView(frame: .init(origin: .zero, size: contentSize))
    textView.string = text
    textView.isEditable = false
    textView.isSelectable = true
    textView.font = NSFont.systemFont(ofSize: NSFont.smallSystemFontSize)
    textView.textContainerInset = NSSize(width: 4, height: 6)
    textView.minSize = .zero
    textView.maxSize = NSSize(width: CGFloat.greatestFiniteMagnitude, height: CGFloat.greatestFiniteMagnitude)
    textView.isVerticallyResizable = true
    textView.isHorizontallyResizable = false
    textView.autoresizingMask = [.width]
    textView.textContainer?.widthTracksTextView = true
    textView.textContainer?.containerSize = NSSize(width: contentSize.width, height: CGFloat.greatestFiniteMagnitude)
    scrollView.documentView = textView
    textView.scrollRangeToVisible(NSRange(location: 0, length: 0))
    return scrollView
  }


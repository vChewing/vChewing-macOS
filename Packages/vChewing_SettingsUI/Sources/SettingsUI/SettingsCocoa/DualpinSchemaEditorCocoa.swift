  // MARK: 匯出

  @objc
  private func exportSchema(_ sender: Any?) {
    guard let text = DualpinSchemaStore.serialize(
      draft.parser,
      schemaURLString: draft.schemaURLString
    )
    else {
      setStatus(DualpinEditorText.exportFailedText(reason: ""))
      return
    }
    guard #available(macOS 10.13, *) else {
      // macOS 10.12 與更早版本（ComDlg32 不可用）：不開面板，改走路徑傾印。
      exportSchemaToFileDump(text)
      return
    }
    let dlgSave = NSSavePanel()
    dlgSave.title = DualpinEditorText.export
    dlgSave.nameFieldStringValue = DualpinEditorText.suggestedFileName(rawTitle: draft.rawTitle)
    if #unavailable(macOS 11) {
      dlgSave.allowedFileTypes = ["json"]
    } else {
      dlgSave.allowedContentTypes = [.json]
    }
    let window = CtlSettingsCocoa.shared?.window
    dlgSave.beginSheetModal(at: window) { [weak self] result in
      guard let self else { return }
      guard result == .OK, let url = dlgSave.url else { return }
      do {
        try text.write(to: url, atomically: true, encoding: .utf8)
        setStatus(DualpinEditorText.exportSucceededText(destination: url.path))
      } catch {
        setStatus(DualpinEditorText.exportFailedText(reason: error.localizedDescription))
      }
    }
  }

  private func exportSchemaToFileDump(_ text: String) {
    do {
      let appSupportURL = try FileManager.default.url(
        for: .applicationSupportDirectory,
        in: .userDomainMask,
        appropriateFor: nil,
        create: true
      )
      let dumpDirURL = appSupportURL.appendingPathComponent("fileDump")
      try FileManager.default.createDirectory(
        at: dumpDirURL,
        withIntermediateDirectories: true
      )
      let formatter = DateFormatter()
      formatter.locale = Locale(identifier: "en_US_POSIX")
      formatter.dateFormat = "ddMMyy-HHmmss"
      let destURL = dumpDirURL.appendingPathComponent(
        "vChewing_DualpinSchema_\(formatter.string(from: Date())).json"
      )
      try text.write(to: destURL, atomically: true, encoding: .utf8)
      setStatus(DualpinEditorText.exportDumpedText(destination: destURL.path))
      NSWorkspace.shared.activateFileViewerSelecting([destURL])
    } catch {
      setStatus(DualpinEditorText.exportFailedText(reason: error.localizedDescription))
    }
  }

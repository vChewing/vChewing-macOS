import Testing

@testable import SettingsUI

// MARK: - DualpinSchemaDraftTests

/// 雙拼方案編輯器之草稿模型（`DualpinSchemaDraft` 暨其共用素材）之測試。
///
/// 兩版渲染器（SwiftUI／AppKit）共用本模型，故本檔即兩者之共同契約之固化。隔離作法比照
/// `PrefsExchangeTests`：以本套件專屬 suite 覆蓋 `OSUtils.defaultsStore`。
@Suite(.serialized)
final class DualpinSchemaDraftTests {
  // MARK: Lifecycle

  init() {
    OSUtils.defaultsStore = InMemoryDefaultsStore()
    OSUtils.isRunningUnitTests = true
    UserDef.resetAll()
  }

  deinit {
    OSUtils.isRunningUnitTests = false
  }

  // MARK: Internal

  // MARK: - ① 範本

  /// 空白範本＝兩內建方案兩表之聯集，且零聲母為固定式 `o`。
  @Test
  func testBlankTemplateMergesTheBuiltinTables() {
    let draft = DualpinSchemaDraft.make(template: .blank, current: nil)
    let mergedInitials = Set(DualpinParser.mspy.initials.keys)
      .union(DualpinParser.gbt17.initials.keys)
    let mergedFinals = Set(DualpinParser.mspy.finals.keys)
      .union(DualpinParser.gbt17.finals.keys)
    #expect(Set(draft.initials.keys) == mergedInitials)
    #expect(Set(draft.finals.keys) == mergedFinals)
    #expect(draft.nullOnset == .fixedKey("o"))
    #expect(draft.rawTitle.isEmpty)
    #expect(draft.rawID == "dualPin.User.Custom")
    #expect(draft.isRawIDAutoGenerated)
  }

  /// 內建範本照抄兩表與政策，惟名稱留白、`rawID` 改發（否則觸 `E9`）。
  @Test
  func testBuiltinTemplateCopiesTablesButNotIdentity() {
    let draft = DualpinSchemaDraft.make(template: .microsoft, current: nil)
    #expect(draft.initials == DualpinParser.mspy.initials)
    #expect(draft.finals == DualpinParser.mspy.finals)
    #expect(draft.nullOnset == DualpinParser.mspy.nullOnset)
    #expect(draft.rawTitle.isEmpty)
    #expect(draft.rawID == "dualPin.User.Custom")
    // 名稱留白 ⇒ E7（引導命名）；`rawID` 已改發 ⇒ 不得有 E9。
    let unnamed = draft.validateReport()
    #expect(unnamed.errors.contains { $0.code == .E7 })
    #expect(!unnamed.errors.contains { $0.code == .E9 })
    // 命名之後即為可用之方案。
    var named = draft
    named.updateTitle("My Copy")
    let report = named.validateReport()
    #expect(report.isUsable)
    #expect(report.errors.isEmpty)
  }

  /// 無現行自訂方案時，「目前自訂」範本退為空白範本。
  @Test
  func testCurrentTemplateFallsBackToBlank() {
    let draft = DualpinSchemaDraft.make(template: .current, current: nil)
    #expect(draft.rawID == "dualPin.User.Custom")
    #expect(draft.nullOnset == .fixedKey("o"))
  }

  /// `rawID` 之自動生成：ASCII 英數以外一律化連字號；無英數者退回 `Custom`。
  @Test
  func testAutoRawIDSlugifiesNames() {
    #expect(DualpinSchemaDraft.autoRawID(forTitle: "My Scheme 1") == "dualPin.User.my-scheme-1")
    #expect(DualpinSchemaDraft.autoRawID(forTitle: "A/B") == "dualPin.User.a-b")
    #expect(DualpinSchemaDraft.autoRawID(forTitle: "   ") == "dualPin.User.Custom")
    #expect(DualpinSchemaDraft.autoRawID(forTitle: "我的方案") == "dualPin.User.Custom")
  }

  // MARK: - ② 身分

  /// 名稱連動 `rawID`；手改 `rawID` 之後即不再連動。
  @Test
  func testRawIDTracksTitleUntilManuallyEdited() {
    var draft = DualpinSchemaDraft.make(template: .microsoft, current: nil)
    draft.updateTitle("My Scheme")
    #expect(draft.rawID == "dualPin.User.my-scheme")
    draft.updateRawID("dualPin.User.mine")
    #expect(!draft.isRawIDAutoGenerated)
    draft.updateTitle("Another")
    #expect(draft.rawID == "dualPin.User.mine")
  }

  /// `rawID` 與內建相衝時報 `E9`、且 `isUsable` 為假（界面據此停用儲存）。
  @Test
  func testConflictingRawIDIsReportedAsE9() {
    var draft = DualpinSchemaDraft.make(template: .microsoft, current: nil)
    draft.updateRawID(DualpinParser.mspy.rawID)
    let report = draft.validateReport()
    #expect(!report.isUsable)
    #expect(report.errors.contains { $0.code == .E9 })
  }

  // MARK: - ③ 按鍵自訂

  /// 兩表互不干擾：同一鍵可同時為某聲母與某尾綴所用。
  @Test
  func testAssignKeepsTheTwoTablesSeparate() throws {
    var draft = DualpinSchemaDraft.make(template: .microsoft, current: nil)
    let initial = try #require(draft.syllables(in: .initials).first)
    let final = try #require(draft.syllables(in: .finals).first)
    draft.assign(key: "q", toSyllable: initial, in: .initials)
    draft.assign(key: "q", toSyllable: final, in: .finals)
    #expect(draft.key(ofSyllable: initial, in: .initials) == "q")
    #expect(draft.key(ofSyllable: final, in: .finals) == "q")
    #expect(draft.syllables(atKey: "q", in: .initials).contains(initial))
    #expect(draft.syllables(atKey: "q", in: .finals).contains(final))
    #expect(!draft.syllables(atKey: "q", in: .initials).contains(final))
  }

  // MARK: - ④ 鍵位格之標註

  /// 表中卻無碼用及之鍵 ⇒ `W5`；碼用及主機保留鍵 ⇒ `W3`（保留鍵不在 27 鍵格內，
  /// 故後者僅見於報告）。
  @Test
  func testKeyAnnotationsFollowTheValidationReport() throws {
    var unused = DualpinSchemaDraft.make(template: .blank, current: nil)
    unused.updateTitle("Unused Keys")
    // 兩表僅留各一鍵、且該二鍵皆不與任何有效詞幹相配 ⇒ 兩鍵皆屬 W5。
    unused.initials = ["b": "b"]
    unused.finals = ["zz": "q"]
    let unusedReport = unused.validateReport()
    let unusedAnnotations = Dictionary(
      uniqueKeysWithValues: unused.keyAnnotations(report: unusedReport).map { ($0.key, $0) }
    )
    let initialKey = try #require(unusedAnnotations["b"])
    let finalKey = try #require(unusedAnnotations["q"])
    #expect(initialKey.isUnusedTableKey)
    #expect(!initialKey.isUsedByAnyCode)
    #expect(finalKey.isUnusedTableKey)
    #expect(!finalKey.isUsedByAnyCode)
    #expect(unusedReport.warnings.contains { $0.code == .W5 })

    var reserved = DualpinSchemaDraft.make(template: .microsoft, current: nil)
    reserved.updateTitle("Reserved Key")
    reserved.finals["ing"] = "`"
    #expect(reserved.validateReport().warnings.contains { $0.code == .W3 })
  }
}
